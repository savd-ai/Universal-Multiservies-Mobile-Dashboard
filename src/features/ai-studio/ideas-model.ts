import type { IdeaSet } from "@/lib/domain/contracts/ai";
import { formatShort } from "@/lib/domain/dates";

// Pure helpers for the Ideas screen: labels (prototype copy), plan month, relative times, campaign short names.

export type StoredIdea = IdeaSet["ideas"][number];

export const PLAN_HREF = "/budget?tab=plans";

const PROVIDER_NAMES: Record<string, string> = { anthropic: "Claude", openai: "OpenAI", gemini: "Gemini", demo: "Demo engine" };
const MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];

/** "Search — Competitor Terms" → "Competitor Terms" (the prototype's `.split('—').pop()`). */
export function shortCampaignName(name: string): string {
  const tail = name.split(/\s[—–-]\s/).pop()?.trim();
  return tail || name;
}

/** The month new ideas are planned for: the one after `today` (YYYY-MM-DD). */
export function nextMonthName(today: string | undefined): string {
  const m = today ? Number(today.slice(5, 7)) : NaN;
  if (!Number.isInteger(m) || m < 1 || m > 12) return "next month's";
  return MONTHS[m % 12] ?? "next month's";
}

export function modelLabel(source: string, model: string | null | undefined): string {
  return model || PROVIDER_NAMES[source] || source;
}

/** Prototype `ideasSourceLabel`, computed: loading copy counts the campaigns being analysed. */
export function ideaSourceLabel(set: Pick<IdeaSet, "source" | "model" | "goal"> | null, opts: { loading: boolean; campaigns: number | null; goal: string }): string {
  if (opts.loading) return `Analyzing ${opts.campaigns ? `${opts.campaigns} campaign${opts.campaigns === 1 ? "" : "s"}` : "your campaigns"} and active signals…`;
  if (!set) return `No ideas yet · goal: ${opts.goal}`;
  return set.source === "demo" ? `Demo suggestions · goal: ${set.goal}` : `Generated by ${modelLabel(set.source, set.model)} · goal: ${set.goal}`;
}

export function ideaCounts(set: Pick<IdeaSet, "ideas"> | null): { total: number; inPlan: number; dismissed: number } {
  const ideas = set?.ideas ?? [];
  return { total: ideas.length, inPlan: ideas.filter((i) => i.inPlan).length, dismissed: ideas.filter((i) => i.dismissed).length };
}

export function visibleIdeas(set: Pick<IdeaSet, "ideas"> | null, showDismissed: boolean): StoredIdea[] {
  return (set?.ideas ?? []).filter((i) => showDismissed || !i.dismissed);
}

/** "just now" · "5 min ago" · "3 h ago" · "yesterday" · "Sep 12" — call after mount only (uses the clock). */
export function relativeTime(iso: string, nowMs: number): string {
  const t = Date.parse(iso);
  if (!Number.isFinite(t)) return "";
  const s = Math.max(0, Math.round((nowMs - t) / 1000));
  if (s < 45) return "just now";
  const min = Math.round(s / 60);
  if (min < 60) return `${min} min ago`;
  const h = Math.round(min / 60);
  if (h < 24) return `${h} h ago`;
  const d = Math.round(h / 24);
  if (d === 1) return "yesterday";
  if (d < 7) return `${d} days ago`;
  return formatShort(iso.slice(0, 10));
}

export function clampBudget(v: number): number {
  return Number.isFinite(v) ? Math.min(10_000_000, Math.max(0, Math.round(v))) : 0;
}
