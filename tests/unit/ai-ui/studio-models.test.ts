// ── Ideas ────────────────────────────────────────────────────────────────────────────────────────────

const IDEA: CampaignIdea = {
  title: "Brand defense on competitor surge",
  type: "Search",
  audience: "Searchers combining your brand with competitor names",
  keywords: ["acme vs competitor", "acme reviews"],
  rationale: "Competitor Terms CPC nearly doubled.",
  dailyBudget: 15,
  impact: "+38 conv / mo",
  confidence: 82,
  citedCampaignIds: ["c8", "c1"],
};

const SET = { id: "s1", goal: "Lower CPA", source: "demo", model: null, ideas: [{ ...IDEA, id: "i1", inPlan: true }, { ...IDEA, id: "i2", dismissed: true }, { ...IDEA, id: "i3" }] } as unknown as IdeaSet;

describe("ideas model", () => {
  it("shortens campaign names like the prototype", () => {
    expect(shortCampaignName("Search — Competitor Terms")).toBe("Competitor Terms");
    expect(shortCampaignName("Demand Gen - Lookalikes")).toBe("Lookalikes");
    expect(shortCampaignName("Plain name")).toBe("Plain name");
  });

  it("names the plan month after today", () => {
    expect(nextMonthName("2026-09-29")).toBe("October");
    expect(nextMonthName("2026-12-02")).toBe("January");
    expect(nextMonthName(undefined)).toBe("next month's");
  });

  it("labels the source like the prototype", () => {
    expect(ideaSourceLabel(null, { loading: true, campaigns: 8, goal: "Q4 season" })).toBe("Analyzing 8 campaigns and active signals…");
    expect(ideaSourceLabel(null, { loading: true, campaigns: null, goal: "Q4 season" })).toBe("Analyzing your campaigns and active signals…");
    expect(ideaSourceLabel(SET, { loading: false, campaigns: 8, goal: "x" })).toBe("Demo suggestions · goal: Lower CPA");
    expect(ideaSourceLabel({ ...SET, source: "anthropic", model: "claude-opus" }, { loading: false, campaigns: 8, goal: "x" })).toBe("Generated by claude-opus · goal: Lower CPA");
    expect(ideaSourceLabel(null, { loading: false, campaigns: 8, goal: "Q4 season" })).toBe("No ideas yet · goal: Q4 season");
  });

  it("counts and filters ideas", () => {
    expect(ideaCounts(SET)).toEqual({ total: 3, inPlan: 1, dismissed: 1 });
    expect(visibleIdeas(SET, false).map((i) => i.id)).toEqual(["i1", "i3"]);
    expect(visibleIdeas(SET, true)).toHaveLength(3);
    expect(visibleIdeas(null, false)).toEqual([]);
  });

  it("formats relative times and clamps budgets", () => {
    const now = Date.parse("2026-09-29T12:00:00Z");
    expect(relativeTime("2026-09-29T11:59:40Z", now)).toBe("just now");
    expect(relativeTime("2026-09-29T11:55:00Z", now)).toBe("5 min ago");
    expect(relativeTime("2026-09-29T09:00:00Z", now)).toBe("3 h ago");
    expect(relativeTime("2026-09-28T10:00:00Z", now)).toBe("yesterday");
    expect(relativeTime("2026-09-12T10:00:00Z", now)).toBe("Sep 12");
    expect(relativeTime("garbage", now)).toBe("");
    expect(clampBudget(-5)).toBe(0);
    expect(clampBudget(Number.NaN)).toBe(0);
    expect(clampBudget(3000.4)).toBe(3000);
    expect(clampBudget(1e9)).toBe(10_000_000);
  });
});

// ── Blueprint ────────────────────────────────────────────────────────────────────────────────────────

function blueprint(over: Partial<Blueprint> = {}): Blueprint {
  return {
    campaignName: "Search — Brand defense",
    type: "Search",
    objective: "Sales",
    bidding: { strategy: "MAXIMIZE_CONVERSIONS", targetCpa: null, targetRoas: null },
    dailyBudget: 15,
    targeting: { locations: ["United States"], languages: ["English"], audiences: [], devices: null, adSchedule: null },
    adGroups: [
      {
        name: "Acme Reviews",
        theme: "Reviews",
        keywords: [{ text: "acme reviews", matchType: "Exact" }],
        negatives: [],
        rsa: { headlines: ["Acme Reviews", "Shop Now", "Secure Checkout"], descriptions: ["Browse the full range and find your fit.", "Order online today."], path1: "Acme", path2: null },
      },
    ],
    campaignNegatives: [{ text: "free", matchType: "Phrase" }],
    sitelinks: [{ text: "Best Sellers", line1: "Our most popular picks", line2: null }],
    callouts: ["Easy Returns"],
    launchChecklist: ["Check conversion tracking"],
    ...over,
  };
}

describe("blueprint model", () => {
  it("references an unchanged idea by id and sends an edited or blank idea inline", () => {
    const original = ideaDraftFrom(IDEA);
    expect(blueprintRequestFor({ setId: "s1", ideaId: "i1", original, draft: original, finalUrl: " https://acme.test/x " })).toEqual({ ideaSetId: "s1", ideaId: "i1", finalUrl: "https://acme.test/x" });
    const edited = { ...original, title: "  Brand defense v2 ", dailyBudget: -4, confidence: 120.4 };
    const req = blueprintRequestFor({ setId: "s1", ideaId: "i1", original, draft: edited });
    expect(req.ideaSetId).toBeUndefined();
    expect(req.idea).toMatchObject({ title: "Brand defense v2", dailyBudget: 0, confidence: 100, citedCampaignIds: ["c8", "c1"] });
    expect(blueprintRequestFor({ draft: blankIdea() }).idea?.title).toBe("New campaign");
  });

  it("validates step-1 ideas and splits lists", () => {
    expect(ideaIssues(blankIdea())).toEqual(["Give the idea a title.", "Add at least one keyword theme for a Search campaign."]);
    expect(ideaIssues({ ...ideaDraftFrom(IDEA), dailyBudget: 0 })).toEqual(["Set a daily budget above zero."]);
    expect(splitList(" a, b ,, A ;c\nd", 3)).toEqual(["a", "b", "c"]);
  });

  it("checks lines with the API validator (ids, wide characters, duplicates, insertions)", () => {
    const bp = blueprint();
    bp.adGroups[0]!.rsa.headlines = ["東京マラソン対応ランニングシューズ", "{KeyWord:Acme Reviews}", "Shop Now", "shop now"];
    const checks = blueprintChecks(bp);
    expect(checks["ag0.h0"]).toMatchObject({ length: 34, ok: false });
    expect(checks["ag0.h1"]).toMatchObject({ length: 12, ok: true });
    expect(checks["ag0.h3"]?.issues).toContain("Duplicate");
    expect(Object.keys(checks)).toEqual(expect.arrayContaining(["ag0.d0", "ag0.p1", "sl0.t", "sl0.l1", "co0"]));
    expect(checks["ag0.p2"]).toBeUndefined();
  });

  it("merges a regenerated section and keeps the rest", () => {
    const cur = blueprint({ campaignName: "Mine", dailyBudget: 99, callouts: ["Mine"] });
    const fresh = blueprint({
      adGroups: [
        { ...blueprint().adGroups[0]!, name: "Fresh", keywords: [{ text: "fresh", matchType: "Broad" }], rsa: { headlines: ["F1", "F2", "F3"], descriptions: ["D1", "D2"], path1: null, path2: null } },
        { name: "Fresh 2", theme: "", keywords: [], negatives: [], rsa: { headlines: ["G1", "G2", "G3"], descriptions: ["E1", "E2"], path1: null, path2: null } },
      ],
      callouts: ["Fresh callout"],
      dailyBudget: 20,
      campaignNegatives: [],
    });
    const s = mergeSection(cur, fresh, "structure");
    expect(s.adGroups.map((g) => g.name)).toEqual(["Fresh", "Fresh 2"]);
    expect(s.adGroups[0]?.rsa.headlines).toEqual(cur.adGroups[0]?.rsa.headlines);
    expect(s.adGroups[1]?.rsa.headlines).toEqual(["G1", "G2", "G3"]);
    expect(s).toMatchObject({ campaignName: "Mine", dailyBudget: 99, callouts: ["Mine"], campaignNegatives: [] });
    const a = mergeSection(cur, fresh, "ads");
    expect(a.adGroups.map((g) => g.name)).toEqual(["Acme Reviews"]);
    expect(a.adGroups[0]?.rsa.headlines).toEqual(["F1", "F2", "F3"]);
    expect(a.callouts).toEqual(["Fresh callout"]);
    expect(a.dailyBudget).toBe(99);
    const r = mergeSection(cur, fresh, "review");
    expect(r).toMatchObject({ dailyBudget: 20, callouts: ["Mine"], campaignName: "Mine" });
  });

  it("edits respect the RSA and blueprint limits", () => {
    let bp = blueprint();
    expect(removeRsaLine(bp, 0, "headlines", 0)).toBe(bp); // already at the 3-headline minimum
    bp = addRsaLine(bp, 0, "headlines");
    expect(bp.adGroups[0]?.rsa.headlines).toHaveLength(4);
    expect(removeRsaLine(bp, 0, "headlines", 3).adGroups[0]?.rsa.headlines).toHaveLength(3);
    for (let i = 0; i < 20; i++) bp = addRsaLine(bp, 0, "headlines");
    expect(bp.adGroups[0]?.rsa.headlines).toHaveLength(15);
    expect(setPath(bp, 0, "path1", "").adGroups[0]?.rsa.path1).toBeNull();
    expect(removeAdGroup(bp, 0)).toBe(bp); // the last group stays
    expect(addAdGroup(bp).adGroups[1]?.name).toBe("Ad group 2");
  });

  it("lists blocking issues per step", () => {
    const bp = blueprint({ campaignName: " ", bidding: { strategy: "TARGET_CPA", targetCpa: null, targetRoas: null }, targeting: { locations: [], languages: [], audiences: [], devices: null, adSchedule: null } });
    bp.adGroups[0]!.keywords = [];
    bp.adGroups[0]!.rsa.headlines = ["An exclamation headline!", "", ""];
    const issues = blueprintIssues(bp, blueprintChecks(bp));
    const texts = issues.map((i) => `${i.step}:${i.text}`);
    expect(texts).toEqual(
      expect.arrayContaining([
        "2:The campaign needs a name.",
        "2:“Acme Reviews” has no keywords.",
        "3:“Acme Reviews” needs at least 3 headlines (has 1).",
        "3:Acme Reviews · Headline 1: Headlines can't contain exclamation marks",
        "3:Acme Reviews · Headline 2: Empty",
        "4:Target CPA needs a value.",
        "4:Add at least one location.",
      ]),
    );
    expect(blueprintIssues(blueprint(), blueprintChecks(blueprint()))).toEqual([]);
  });

  it("labels line ids, names the CSV and detects edits", () => {
    const bp = blueprint();
    expect(lineLabel("ag0.h2", bp)).toBe("Acme Reviews · Headline 3");
    expect(lineLabel("ag0.p1", bp)).toBe("Acme Reviews · Path 1");
    expect(lineLabel("sl1.l2", bp)).toBe("Sitelink 2 line 2");
    expect(lineLabel("co0", bp)).toBe("Callout 1");
    expect(csvFilename("Search — Brand defense!")).toBe("search-brand-defense-editor.csv");
    expect(csvFilename("   ")).toBe("blueprint-editor.csv");
    expect(matchNotation({ text: "acme", matchType: "Exact" })).toBe("[acme]");
    expect(matchNotation({ text: "acme", matchType: "Phrase" })).toBe('"acme"');
    expect(isEdited(bp, blueprint())).toBe(false);
    expect(isEdited({ ...bp, dailyBudget: 1 }, blueprint())).toBe(true);
  });
});

// ── Ad copy ──────────────────────────────────────────────────────────────────────────────────────────

const line = (key: string, text: string, over: Partial<CopyLine> = {}): CopyLine => ({ key, text, pin: null, locked: false, ...over });

describe("ad copy model", () => {
  it("builds the request from the brief", () => {
    expect(adCopyRequestFrom({ ...EMPTY_FORM, product: " Trail shoes ", keywords: "trail shoes, waterproof trail shoes,", usps: "Free returns\nVibram soles", finalUrl: " ", campaignId: "c2" })).toEqual({
      product: "Trail shoes",
      audience: "",
      keywords: ["trail shoes", "waterproof trail shoes"],
      usps: ["Free returns", "Vibram soles"],
      tone: "confident",
      campaignId: "c2",
    });
    expect(formIssues(EMPTY_FORM)).toHaveLength(1);
    expect(formIssues({ ...EMPTY_FORM, keywords: "shoes" })).toEqual([]);
  });

  it("turns results into editable lines with generation-unique keys", () => {
    const r = { headlines: [{ text: "H1", pin: 1, angle: "brand" }], descriptions: [{ text: "D1", pin: null }], path1: { text: "Trail" }, path2: null } as unknown as AdCopyResult;
    expect(copyFromResult(r, 3)).toEqual({ headlines: [{ key: "g3h0", text: "H1", pin: 1, locked: false, angle: "brand" }], descriptions: [{ key: "g3d0", text: "D1", pin: null, locked: false }], path1: "Trail", path2: "", pathsLocked: false });
  });

  it("regenerates unlocked lines in place without repeating locked texts", () => {
    const cur = [line("a", "Keep me", { locked: true }), line("b", "Old 1", { pin: 2 }), line("c", "Old 2")];
    const fresh = [line("x", "keep me"), line("y", "New 1"), line("z", "")];
    const merged = mergeUnlocked(cur, fresh);
    expect(merged.map((l) => l.text)).toEqual(["Keep me", "New 1", "Old 2"]);
    expect(merged[1]).toMatchObject({ key: "b", pin: 2, locked: false });
    const state: CopyState = { headlines: cur, descriptions: [], path1: "a", path2: "b", pathsLocked: true };
    expect(mergeCopy(state, { headlines: fresh, descriptions: [], path1: "x", path2: "y", pathsLocked: false })).toMatchObject({ path1: "a", path2: "b" });
    expect(mergeCopy({ ...state, pathsLocked: false }, { headlines: fresh, descriptions: [], path1: "x", path2: "y", pathsLocked: false })).toMatchObject({ path1: "x", path2: "y" });
  });

  it("checks lines with the API ids and validator", () => {
    const c: CopyState = { headlines: [line("a", "Shop the Spring Sale Today Online"), line("b", "Great deals!"), line("c", "Great deals!")], descriptions: [line("d", "Short.")], path1: "Trail-Running-Shoes", path2: "", pathsLocked: false };
    const checks = copyChecks(c);
    expect(checks.h0).toMatchObject({ length: 33, ok: false });
    expect(checks.h1?.issues).toContain("Headlines can't contain exclamation marks");
    expect(checks.h2?.issues).toContain("Duplicate");
    expect(checks.d0?.ok).toBe(true);
    expect(checks.p1).toMatchObject({ length: 19, ok: false });
    expect(checks.p2).toBeUndefined();
  });

  it("previews pinned lines in their position", () => {
    const lines = [line("a", "A"), line("b", "B", { pin: 1 }), line("c", ""), line("d", "D", { pin: 3 }), line("e", "E")];
    expect(previewOrder(lines, 3)).toEqual(["B", "A", "D"]);
    expect(previewOrder([line("a", "A", { pin: 2 })], 3)).toEqual(["A"]);
  });

  it("formats copy-all text and pin notes", () => {
    const c: CopyState = { headlines: [line("a", "H one", { pin: 1 }), line("b", ""), line("c", "H two")], descriptions: [line("d", "D one")], path1: "Trail", path2: "Shoes", pathsLocked: false };
    expect(formatCopyText(c)).toBe("Headlines\n1. H one  [pin 1]\n2. H two\n\nDescriptions\n1. D one\n\nPath: /Trail/Shoes");
    expect(pinNotes(c)).toEqual(["1 headline pinned. Pinning lowers ad strength; pin only what must show.", "A responsive search ad needs at least 3 headlines.", "A responsive search ad needs at least 2 descriptions."]);
  });
});

// ── Negatives ────────────────────────────────────────────────────────────────────────────────────────

const cand = (over: Partial<NegativeCandidate>): NegativeCandidate => ({
  id: "t:c2:c2-ag1:free running shoes",
  kind: "term",
  term: "free running shoes",
  negativeText: "free",
  rules: ["high_cost_no_conv", "modifier"],
  campaignId: "c2",
  campaignName: "Generic — Running Shoes",
  adGroupId: "c2-ag1",
  cost: 1355.72,
  clicks: 729,
  impressions: 13974,
  conversions: 0,
  reasons: ["$1,356 spent with no conversions", "Irrelevant modifier “free”"],
  suggestedMatch: "Phrase",
  suggestedLevel: "account_list",
  monthlySavings: 1355.72,
  verdict: "negative",
  aiReason: "Irrelevant intent and no conversions.",
  ...over,
});

describe("negatives model", () => {
  const list = [
    cand({}),
    cand({ id: "t:c8:c8-ag1:stridemax login", term: "stridemax login", negativeText: "login", rules: ["competitor"], campaignId: "c8", adGroupId: "c8-ag1", suggestedLevel: "ad_group", suggestedMatch: "Exact", verdict: "review", monthlySavings: 400 }),
    cand({ id: "n:pdf", kind: "ngram", term: "pdf", negativeText: "pdf", rules: ["ngram"], campaignId: "", campaignName: "All campaigns", adGroupId: "", verdict: "negative", monthlySavings: 600 }),
    cand({ id: undefined, term: "acme careers", negativeText: "acme careers", rules: ["modifier"], campaignId: "c1", adGroupId: "c1-ag1", verdict: "keep", monthlySavings: 100 }),
  ];

  it("filters and counts by reason and verdict", () => {
    expect(filterCandidates(list, { reason: "modifier", verdict: "all" })).toHaveLength(2);
    expect(filterCandidates(list, { reason: "all", verdict: "negative" }).map((c) => c.term)).toEqual(["free running shoes", "pdf"]);
    expect(filterCandidates(list, { reason: "ngram", verdict: "review" })).toEqual([]);
    const counts = countCandidates(list);
    expect(counts.verdicts).toEqual({ negative: 2, review: 1, keep: 1 });
    expect(counts.reasons).toMatchObject({ modifier: 2, competitor: 1, ngram: 1, high_cost_no_conv: 1, low_ctr: 0 });
  });

  it("derives stable keys, notation and brand hits", () => {
    expect(candidateKey(list[3] as NegativeCandidate)).toBe("t:c1:c1-ag1:acme careers");
    expect(notation("how to", "Exact")).toBe("[how to]");
    expect(notation("how to", "Phrase")).toBe('"how to"');
    expect(brandHit("acme careers", ["acme"])).toBe("acme");
    expect(brandHit("acmeshoes careers", ["acme"])).toBeNull();
    expect(brandHit("careers", [" "])).toBeNull();
  });

  it("builds the add_negatives payload: overrides, levels, n-gram expansion, brand refusal, dedupe", () => {
    const p = buildNegativesPayload([...list, cand({ id: "dup" })], { match: { "t:c2:c2-ag1:free running shoes": "Exact" }, campaignIds: ["c1", "c2"], brandTerms: ["acme"] });
    expect(p.negatives).toEqual([
      { text: "free", matchType: "Exact", campaignId: "c2" },
      { text: "login", matchType: "Exact", campaignId: "c8", adGroupId: "c8-ag1" },
      { text: "pdf", matchType: "Phrase", campaignId: "c1" },
      { text: "pdf", matchType: "Phrase", campaignId: "c2" },
      { text: "free", matchType: "Phrase", campaignId: "c2" },
    ]);
    expect(p.skippedBrand).toEqual(["acme careers"]);
    expect(p.expanded).toBe(1);
    expect(p.truncated).toBe(0);
  });

  it("caps one action at 200 lines", () => {
    const many = Array.from({ length: 250 }, (_, i) => cand({ id: `t${i}`, negativeText: `term ${i}` }));
    const p = buildNegativesPayload(many, { match: {}, campaignIds: [], brandTerms: [] });
    expect(p.negatives).toHaveLength(200);
    expect(p.truncated).toBe(50);
  });

  it("sums the savings of the selection", () => {
    expect(selectedSavings(list, new Set(["n:pdf", "t:c1:c1-ag1:acme careers", "missing"]))).toBe(700);
  });
});
