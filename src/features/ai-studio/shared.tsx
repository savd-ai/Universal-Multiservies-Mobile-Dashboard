/** Mono source label + the fallback reason and validator repairs in small print. */
export function AiSourceLine({ source, model, fallbackReason, warnings, demoLabel, aiLabel, className, children }: { source?: string; model?: string | null; fallbackReason?: string; warnings?: string[]; demoLabel: string; aiLabel?: string; className?: string; children?: React.ReactNode }) {
  if (!source) return null;
  const label = source === "demo" ? demoLabel : `${aiLabel ?? "Generated by"} ${modelLabel(source, model)}`;
  return (
    <div className={cn("flex flex-col gap-1", className)}>
      <div className="flex flex-wrap items-center gap-x-4 gap-y-1.5">
        <span className="font-mono text-meta tracking-label text-faint uppercase">{label}</span>
        {children}
      </div>
      {fallbackReason ? <span className="text-xs text-faint">{`AI unavailable: ${fallbackReason}`}</span> : null}
      {warnings?.map((w) => (
        <span key={w} className="text-xs text-faint">
          {w}
        </span>
      ))}
    </div>
  );
}

const BLOCKING = /^(too long|empty|duplicate|too many words|missing)/i;

/** Validation issues as pills: length / empty / duplicate block the import (crit), editorial lint warns. */
export function IssueList({ issues, className }: { issues: readonly string[]; className?: string }) {
  if (!issues.length) return null;
  return (
    <div className={cn("flex flex-wrap gap-1.5", className)}>
      {issues.map((i) => (
        <span key={i} className={cn("rounded-pill px-2 py-0.5 text-[11px] leading-tight", BLOCKING.test(i) ? "bg-crit-t text-crit" : "bg-warn-t text-warn")}>
          ▲ {i}
        </span>
      ))}
    </div>
  );
}

interface TextLineRowProps {
  label: string;
  ariaLabel: string;
  value: string;
  onChange: (v: string) => void;
  check?: AdTextCheck;
  limit: number;
  placeholder?: string;
  onRemove?: () => void;
  canRemove?: boolean;
  /** extra controls between the counter and × (pin, lock…) */
  aside?: React.ReactNode;
  meta?: React.ReactNode;
  showOk?: boolean;
  dimmed?: boolean;
}

/** One ad asset line: text input, live display-length counter (wide chars count 2), issues and actions. */
export function TextLineRow({ label, ariaLabel, value, onChange, check, limit, placeholder, onRemove, canRemove = true, aside, meta, showOk, dimmed }: TextLineRowProps) {
  const issues = check?.issues ?? [];
  const bad = issues.length > 0;
  return (
    <div className={cn("flex flex-col gap-1.5 rounded-mini border bg-fill px-3 py-2 transition-colors focus-within:border-accent/60", bad ? "border-crit/30" : "border-tone/8", dimmed && "opacity-80")}>
      <div className="flex flex-wrap items-center gap-x-2.5 gap-y-1.5">
        <span className="w-8 shrink-0 font-mono text-micro tracking-label text-faint uppercase">{label}</span>
        <input aria-label={ariaLabel} value={value} placeholder={placeholder} onChange={(e) => onChange(e.target.value)} className="min-w-[140px] flex-1 bg-transparent py-0.5 text-[13px] text-fg outline-none placeholder:text-faint" />
        {/* trailing controls wrap under the text on narrow screens */}
        <span className="ml-auto flex shrink-0 items-center gap-2.5">
          {meta}
          {showOk && check && !bad ? (
            <span className="rounded-pill bg-teal-t px-1.5 py-px font-mono text-micro text-accent" title="Passes the Google Ads length and policy checks">
              ✓ OK
            </span>
          ) : null}
          <CharCounter length={check?.length ?? value.length} max={limit} />
          {aside}
          {onRemove ? (
            <IconButton label={`Remove ${ariaLabel.toLowerCase()}`} onClick={onRemove} disabled={!canRemove} className="disabled:opacity-30">
              ×
            </IconButton>
          ) : null}
        </span>
      </div>
      <IssueList issues={issues} className="pl-[42px]" />
    </div>
  );
}

function displayUrl(finalUrl: string | undefined, path1?: string | null, path2?: string | null): string {
  let host = "example.com";
  if (finalUrl) {
    try {
      host = new URL(/^https?:\/\//i.test(finalUrl) ? finalUrl : `https://${finalUrl}`).hostname.replace(/^www\./, "");
    } catch {
      /* keep the placeholder */
    }
  }
  return [host, path1, path2].filter(Boolean).join("/");
}

/** Search-results preview of a responsive search ad (first three headlines, two descriptions). */
export function AdPreview({ headlines, descriptions, path1, path2, finalUrl, className }: { headlines: string[]; descriptions: string[]; path1?: string | null; path2?: string | null; finalUrl?: string; className?: string }) {
  const h = headlines.map(insertionDefaults).filter((t) => t.trim()).slice(0, 3);
  const d = descriptions.map(insertionDefaults).filter((t) => t.trim()).slice(0, 2);
  return (
    <div className={cn("flex flex-col gap-1 rounded-mini border border-line bg-surface p-4", className)} aria-label="Ad preview">
      <div className="flex items-center gap-2 text-[11px] text-muted-3">
        <span className="font-semibold text-fg">Sponsored</span>
        <span aria-hidden>·</span>
        <span className="truncate">{displayUrl(finalUrl, path1, path2)}</span>
      </div>
      <div className="font-display text-[17px] leading-snug font-medium text-accent">{h.length ? h.join(" | ") : "Your headlines appear here"}</div>
      <div className="text-[13px] leading-normal text-muted">{d.join(" ") || "Descriptions appear here."}</div>
    </div>
  );
}

// ── Campaign index ───────────────────────────────────────────────────────────────────────────────────

const CAMPAIGNS_SPEC: QuerySpecInput = { source: "google_ads", metrics: ["cost"], dimensions: ["campaign"], dateRange: { preset: "last_30d" }, sort: [{ key: "cost", dir: "desc" }] };

export interface CampaignRef {
  id: string;
  name: string;
  cost: number;
}

/** Campaigns with spend in the last 30 days (shared cached query), for citations, pickers and counts. */
export function useCampaignIndex() {
  const q = useQueryResult(CAMPAIGNS_SPEC);
  return useMemo(() => {
    const list: CampaignRef[] = (q.data?.rows ?? []).map((r) => ({ id: String(r.campaign_id ?? r.campaign ?? ""), name: String(r.campaign ?? r.campaign_id ?? ""), cost: typeof r.cost === "number" ? r.cost : 0 }));
    return { list, byId: new Map(list.map((c) => [c.id, c])), loaded: !!q.data };
  }, [q.data]);
}

// ── Clock (relative times render after hydration; 0 on the server and during hydration) ──────────────

let nowMs = 0;
let timer: ReturnType<typeof setInterval> | null = null;
const listeners = new Set<() => void>();

function subscribeNow(cb: () => void): () => void {
  listeners.add(cb);
  if (!timer) {
    nowMs = Date.now();
    timer = setInterval(() => {
      nowMs = Date.now();
      listeners.forEach((l) => l());
    }, 30_000);
  }
  return () => {
    listeners.delete(cb);
    if (!listeners.size && timer) {
      clearInterval(timer);
      timer = null;
    }
  };
}

const nowSnapshot = () => nowMs || (nowMs = Date.now());

/** Current time in ms, refreshed every 30 s; 0 until hydrated. */
export function useNow(): number {
  return useSyncExternalStore(subscribeNow, nowSnapshot, () => 0);
}
